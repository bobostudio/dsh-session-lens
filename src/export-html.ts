/**
 * Export renderer: (story-filtered, redacted events + analytics) → ONE
 * self-contained HTML file.
 *
 * Properties:
 * - Fully static: no JavaScript, no external resources, no network fetches.
 *   Collapsible sections use native <details>. Charts are inline SVG.
 * - XSS-safe by construction: every dynamic string passes through esc();
 *   a restrictive CSP meta tag (default-src 'none') is belt-and-braces.
 * - Bilingual chrome (zh default / en); message content stays untouched.
 * - Privacy: only whitelisted story events are rendered (see redact.ts), so
 *   the system prompt and other internal plumbing can never appear.
 */

