function buildCss(theme: ExportTheme): string {
  const root =
    theme === "dark"
      ? ":root{color-scheme:dark}"
      : theme === "light"
        ? ":root{color-scheme:light}"
        : ":root{color-scheme:light dark}";
  if (theme === "light") return `${root}\n${LIGHT_CSS}`;
  if (theme === "dark") return `${root}\n${LIGHT_CSS}\n${DARK_CSS}`;
  return `${root}\n${LIGHT_CSS}\n@media (prefers-color-scheme:dark){\n${DARK_CSS}\n}`;
}

/**
 * Render the full export document. `events` should be the session's expanded
 * event stream (unfiltered — story filtering and redaction happen here).
 */
export function renderSessionHtml(
  events: SessionEvent[],
  analyticsInput?: SessionAnalytics,
  header?: SessionHeader | null,
  options: ExportOptions = {},
): string {
  const lang: Lang = options.lang === "en" ? "en" : "zh";
  const theme: ExportTheme = options.theme ?? "dark";
  const s: Strings = STRINGS[lang];
  const analytics = analyticsInput ?? analyzeSession(events, header);
  const story = redactEvents(filterStoryEvents(events), options);

  const title = analytics.title ?? analytics.sessionId ?? "session";
  const modelLabel = analytics.models.join(", ") || "—";
  const truncated = (options.maxTextLength === undefined ? 2000 : options.maxTextLength) !== null;
  const masked = options.maskPaths !== false;
  const statusLabel = analytics.status === "active" ? s.statusActive : analytics.status;

  return `<!doctype html>
<html lang="${lang === "zh" ? "zh-CN" : "en"}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:;">
<title>${esc(title)} · ${esc(s.report)}</title>
<style>${buildCss(theme)}</style>
</head>
<body>
<main>
<header class="report">
<h1>${esc(title)}</h1>
<div class="meta">
<span>${esc(s.model)}: ${esc(modelLabel)}</span>
<span>${esc(s.status)}: ${esc(statusLabel)}</span>
<span>${esc(s.createdAt)}: ${esc(fmtTime(analytics.createdAt ?? analytics.firstEventAt, lang))}</span>
<span>${esc(s.duration)}: ${esc(formatDuration(analytics.durationMs))}</span>
<span>${esc(s.turn)}: ${analytics.turns}</span>
<span>${esc(s.messages)}: ${analytics.userMessages + analytics.assistantMessages}</span>
<span>${esc(s.eventCount)}: ${analytics.eventCount}</span>
</div>
</header>
${renderStats(analytics, s, lang)}
<h2>${esc(s.replay)}</h2>
<section class="replay">
${renderReplay(story, s)}
</section>
<footer>
<div>${esc(s.generatedBy)} · <a href="https://github.com/bobostudio/dsh-session-lens">github.com/bobostudio/dsh-session-lens</a> · ${esc(truncated ? s.truncatedNote : s.fullNote)}</div>
<div class="privacy">${esc(masked ? s.privacyNote : s.privacyNoteFull)}</div>
</footer>
</main>
</body>
</html>
`;
}
